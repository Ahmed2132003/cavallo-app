from django.db import models

from core.models import TimestampedModel


class BusinessDailyStats(TimestampedModel):
    """
    Part P-084. One row per (business, date): a daily rollup of that
    business's engagement, computed by analytics.tasks.compute_daily_stats
    (Architecture Section 17: daily rollup job, never live aggregation).

    ONLY metrics this system genuinely tracks are stored here:
      - new_followers            <- social.Follow rows created that day
      - total_likes_received     <- social.Like rows on the business's Post/Reel
      - total_comments_received  <- social.Comment rows on the business's Post/Reel
      - total_story_views        <- stories.StoryView rows on the business's Stories

    Part P-093 additions (additive migration 0002), all genuinely backed:
      - new_ratings_count        <- ratings.Rating rows CREATED that day.
                                    A customer re-rating a business updates
                                    their single row (unique per customer +
                                    business), so only first-time ratings
                                    are counted, not later edits.
      - average_rating_snapshot  <- BusinessProfile.average_rating copied at
                                    rollup time: a POINT-IN-TIME SNAPSHOT
                                    for trend lines, NOT a live value.
      - active_products_count /
        published_posts_count /
        published_reels_count    <- snapshots of the catalog totals at
                                    rollup time (catalog-growth chart).

    DOCUMENTED GAP (not a bug): product views and profile views are NOT
    tracked anywhere in this system, so there is deliberately NO field for
    them. Do not add one without first building a real tracking mechanism.

    ``date`` is a UTC calendar date (settings.TIME_ZONE == "UTC").
    """

    business = models.ForeignKey(
        "businesses.BusinessProfile",
        on_delete=models.CASCADE,
        related_name="daily_stats",
    )
    date = models.DateField()
    new_followers = models.PositiveIntegerField(default=0)
    total_likes_received = models.PositiveIntegerField(default=0)
    total_comments_received = models.PositiveIntegerField(default=0)
    total_story_views = models.PositiveIntegerField(default=0)
    # Part P-093 (see class docstring).
    new_ratings_count = models.PositiveIntegerField(default=0)
    # Point-in-time snapshot, same precision as
    # BusinessProfile.average_rating (max_digits=3, decimal_places=2).
    average_rating_snapshot = models.DecimalField(
        max_digits=3, decimal_places=2, default=0
    )
    active_products_count = models.PositiveIntegerField(default=0)
    published_posts_count = models.PositiveIntegerField(default=0)
    published_reels_count = models.PositiveIntegerField(default=0)
    # Part BI-02: set (UTC) when the product/content rollups for this day
    # were computed. NULL = the day has no BI rollups, so dashboard view
    # metrics for it are reported as null instead of a fake 0. It is also
    # the real source of every ``data_updated_at`` in the dashboard APIs.
    # Not exposed by BusinessDailyStatsSerializer (explicit field list).
    bi_rollups_computed_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        unique_together = ("business", "date")

    def __str__(self):
        return f"BusinessDailyStats(business={self.business_id}, date={self.date})"


class ContentKind(models.TextChoices):
    POST = "post", "Post"
    REEL = "reel", "Reel"


class ProductViewEvent(models.Model):
    """
    Part BI-02. RAW, append-only product view (source of truth; every counter
    is rebuilt from these rows).

    - event_id: UUID generated by the client; UNIQUE, so a retried upload
      can never double count.
    - viewer_key: HMAC-SHA256 of the user id (logged in) or of the install
      id (anonymous). Never an IP, never a raw id (analytics/tracking.py).
    - view_date: the UTC calendar day of occurred_at.
    - Unique View = one viewer_key per product per view_date.
    """

    event_id = models.UUIDField(unique=True)
    viewer_key = models.CharField(max_length=64)
    product = models.ForeignKey(
        "products.Product",
        on_delete=models.PROTECT,
        related_name="view_events",
    )
    business = models.ForeignKey(
        "businesses.BusinessProfile",
        on_delete=models.PROTECT,
        related_name="product_view_events",
    )
    occurred_at = models.DateTimeField()
    view_date = models.DateField()
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        indexes = [
            models.Index(
                fields=["product", "view_date", "viewer_key"],
                name="an_pve_prod_date_viewer_idx",
            ),
            models.Index(
                fields=["business", "view_date", "viewer_key"],
                name="an_pve_biz_date_viewer_idx",
            ),
            models.Index(fields=["view_date"], name="an_pve_date_idx"),
        ]

    def __str__(self):
        return f"ProductViewEvent(product={self.product_id}, date={self.view_date})"

    def save(self, *args, **kwargs):
        if not self._state.adding:
            raise RuntimeError("ProductViewEvent is append-only.")
        super().save(*args, **kwargs)


class ContentViewEvent(models.Model):
    """
    Part BI-02. RAW, append-only Post/Reel view. Same rules as
    ProductViewEvent. watch_ms is only filled for reels (milliseconds
    actually watched); a reel view under ANALYTICS_REEL_MIN_WATCH_MS is
    never stored.
    """

    event_id = models.UUIDField(unique=True)
    viewer_key = models.CharField(max_length=64)
    content_kind = models.CharField(max_length=10, choices=ContentKind.choices)
    object_id = models.PositiveIntegerField()
    business = models.ForeignKey(
        "businesses.BusinessProfile",
        on_delete=models.PROTECT,
        related_name="content_view_events",
    )
    occurred_at = models.DateTimeField()
    view_date = models.DateField()
    watch_ms = models.PositiveIntegerField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        constraints = [
            models.CheckConstraint(
                condition=models.Q(content_kind__in=["post", "reel"]),
                name="an_cve_kind_valid",
            ),
        ]
        indexes = [
            models.Index(
                fields=["content_kind", "object_id", "view_date", "viewer_key"],
                name="an_cve_obj_date_viewer_idx",
            ),
            models.Index(
                fields=["business", "view_date", "viewer_key"],
                name="an_cve_biz_date_viewer_idx",
            ),
            models.Index(fields=["view_date"], name="an_cve_date_idx"),
        ]

    def __str__(self):
        return (
            f"ContentViewEvent({self.content_kind}:{self.object_id}, "
            f"date={self.view_date})"
        )

    def save(self, *args, **kwargs):
        if not self._state.adding:
            raise RuntimeError("ContentViewEvent is append-only.")
        super().save(*args, **kwargs)


class ProductDailyStats(TimestampedModel):
    """
    Part BI-02. Derived rollup, one row per (product, UTC day) that had any
    activity (sparse). Built by analytics.rollups from ProductViewEvent,
    chat.ConversationProductInterest and social.Save with update_or_create,
    so recomputing a past day is safe. Orders are NOT rolled up: dashboards
    read the indexed orders table directly.
    """

    business = models.ForeignKey(
        "businesses.BusinessProfile",
        on_delete=models.CASCADE,
        related_name="product_daily_stats",
    )
    product = models.ForeignKey(
        "products.Product",
        on_delete=models.CASCADE,
        related_name="daily_stats",
    )
    date = models.DateField()
    views = models.PositiveIntegerField(default=0)
    unique_views = models.PositiveIntegerField(default=0)
    interests = models.PositiveIntegerField(default=0)
    saves = models.PositiveIntegerField(default=0)

    class Meta:
        constraints = [
            models.UniqueConstraint(
                fields=["product", "date"], name="an_pds_unique_product_date"
            ),
        ]
        indexes = [
            models.Index(fields=["business", "date"], name="an_pds_biz_date_idx"),
        ]

    def __str__(self):
        return f"ProductDailyStats(product={self.product_id}, date={self.date})"


class ContentDailyStats(TimestampedModel):
    """
    Part BI-02. Derived rollup, one row per (Post|Reel, UTC day) with any
    activity. views/unique_views come from ContentViewEvent; likes, comments,
    saves and shares are the social.Like/Comment/Save/Share rows CREATED that
    day (an unlike deletes its row, so counts reflect surviving rows, same
    rule as BusinessDailyStats). ``shares`` = in-app share events only.
    """

    business = models.ForeignKey(
        "businesses.BusinessProfile",
        on_delete=models.CASCADE,
        related_name="content_daily_stats",
    )
    content_kind = models.CharField(max_length=10, choices=ContentKind.choices)
    object_id = models.PositiveIntegerField()
    date = models.DateField()
    views = models.PositiveIntegerField(default=0)
    unique_views = models.PositiveIntegerField(default=0)
    likes = models.PositiveIntegerField(default=0)
    comments = models.PositiveIntegerField(default=0)
    saves = models.PositiveIntegerField(default=0)
    shares = models.PositiveIntegerField(default=0)

    class Meta:
        constraints = [
            models.UniqueConstraint(
                fields=["content_kind", "object_id", "date"],
                name="an_cds_unique_obj_date",
            ),
        ]
        indexes = [
            models.Index(
                fields=["business", "date", "content_kind"],
                name="an_cds_biz_date_kind_idx",
            ),
        ]

    def __str__(self):
        return (
            f"ContentDailyStats({self.content_kind}:{self.object_id}, "
            f"date={self.date})"
        )


class ExternalContentMetricSnapshot(models.Model):
    """
    Part BI-02. A number the OWNER typed in (or, later, a provider synced)
    about a Post/Reel on another platform. Snapshots only accumulate (rows
    are never updated), so the history of a metric is kept and the "latest"
    is the row with the greatest captured_at. External numbers are never
    mixed with internal ones. No scraping: nothing in this codebase fetches
    from a social platform.
    """

    class Platform(models.TextChoices):
        INSTAGRAM = "instagram", "Instagram"
        FACEBOOK = "facebook", "Facebook"
        TIKTOK = "tiktok", "TikTok"

    class MetricType(models.TextChoices):
        VIEWS = "views", "Views"
        LIKES = "likes", "Likes"
        SHARES = "shares", "Shares"
        SAVES = "saves", "Saves"

    class Source(models.TextChoices):
        MANUAL = "manual", "Manual"
        SYNCED = "synced", "Synced"

    business = models.ForeignKey(
        "businesses.BusinessProfile",
        on_delete=models.PROTECT,
        related_name="external_metric_snapshots",
    )
    content_type = models.CharField(max_length=10, choices=ContentKind.choices)
    content_id = models.PositiveIntegerField()
    platform = models.CharField(max_length=20, choices=Platform.choices)
    metric_type = models.CharField(max_length=20, choices=MetricType.choices)
    metric_value = models.PositiveBigIntegerField()
    captured_at = models.DateTimeField()
    source = models.CharField(
        max_length=10, choices=Source.choices, default=Source.MANUAL
    )
    external_reference = models.CharField(max_length=255, blank=True, default="")
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        indexes = [
            models.Index(
                fields=[
                    "business",
                    "content_type",
                    "content_id",
                    "platform",
                    "metric_type",
                    "captured_at",
                ],
                name="an_ext_lookup_idx",
            ),
        ]

    def __str__(self):
        return (
            f"{self.platform}/{self.metric_type}={self.metric_value} "
            f"({self.content_type}:{self.content_id})"
        )

    def save(self, *args, **kwargs):
        if not self._state.adding:
            raise RuntimeError("ExternalContentMetricSnapshot is append-only.")
        super().save(*args, **kwargs)
